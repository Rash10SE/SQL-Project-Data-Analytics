/*
===============================================================================
Magnitude Analysis
===============================================================================
Script Purpose:
    This script analyzes the distribution and magnitude of business metrics
    across different customer and product dimensions.

    It groups data by relevant attributes to identify patterns and understand
    how customers, products, costs, and revenue are distributed.

Main Operations:
    - Analyze customer distribution by country and gender.
    - Examine product distribution across categories.
    - Calculate average product costs by category.
    - Evaluate revenue contribution by product category.
    - Identify revenue generated by individual customers.

Key SQL Concepts:
    - GROUP BY
    - Aggregate Functions
    - SUM()
    - AVG()
    - COUNT()
===============================================================================
*/

-- MAGNITUDE ANALYSIS: ∑ [MEASURE] by [DIMENSION] -> Ex: Total Sales BY Country, AVG Price BY Product...
-- Total Customers by Country
SELECT country ,COUNT(customer_key) AS total_customers
FROM gold.gold_dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-- Total Customers by Gender
SELECT gender, COUNT(customer_key) AS total_customers
FROM gold.gold_dim_customers
GROUP BY gender
ORDER BY total_customers DESC;

-- Total Products by Category
SELECT category, COUNT(product_id) AS total_products
FROM gold.gold_dim_products
GROUP BY category
ORDER BY total_products DESC;

-- The Average costs in each Category
SELECT category, AVG(cost) AS avg_costs
FROM gold.gold_dim_products
GROUP BY category
ORDER BY avg_costs DESC;

-- Total Revenue for each Category
SELECT p.category, SUM(sales_amount) AS total_revenue
FROM gold.gold_fact_sales s
LEFT JOIN gold.gold_dim_products p
ON s.product_key = p.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- Total Revenue generated by each Customer
SELECT customer_key, SUM(sales_amount) AS total_revenue
FROM gold.gold_fact_sales
GROUP BY customer_key
ORDER BY total_revenue DESC;

-- Distribution of sold items across countries
SELECT c.country, COUNT(s.product_key) AS total_sold_items
FROM gold.gold_fact_sales s
LEFT JOIN gold.gold_dim_customers c
ON s.customer_key = c.customer_key
LEFT JOIN gold.gold_dim_products p
ON s.product_key = p.product_key
GROUP BY c.country
ORDER BY total_sold_items DESC;
